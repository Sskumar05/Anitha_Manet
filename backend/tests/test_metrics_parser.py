    metrics = parse_flowmon_xml(xml_file, routing_control_packets=50)

    assert metrics["tx_packets"] == 20
    assert metrics["rx_packets"] == 0
    assert metrics["lost_packets"] == 20
    assert metrics["pdr"] == 0.0
    assert metrics["delay_ms"] is None
    assert metrics["overhead_ratio"] is None


