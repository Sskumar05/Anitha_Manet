def test_sqlite_nullable_delay_persistence(tmp_path: Path):
    """
    Verifies database persistence:
    1. Saving a result with delay_ms=None stores SQL NULL and retrieves None.
    2. Saving a result with delay_ms=0.0 preserves numeric 0.0 (historical record).
    3. Saving a normal numeric delay preserves the exact float.
    """
    import sqlite3
    db_file = tmp_path / "test.db"
    with sqlite3.connect(db_file) as conn:
        conn.execute("CREATE TABLE simulation_runs (run_id TEXT PRIMARY KEY, delay_ms REAL)")
        conn.execute("INSERT INTO simulation_runs VALUES (?, ?)", ("sim_test_null", None))
        conn.execute("INSERT INTO simulation_runs VALUES (?, ?)", ("sim_test_zero", 0.0))
        conn.execute("INSERT INTO simulation_runs VALUES (?, ?)", ("sim_test_num", 12.45))

        row_null = conn.execute("SELECT delay_ms FROM simulation_runs WHERE run_id = 'sim_test_null'").fetchone()
        row_zero = conn.execute("SELECT delay_ms FROM simulation_runs WHERE run_id = 'sim_test_zero'").fetchone()
        row_num = conn.execute("SELECT delay_ms FROM simulation_runs WHERE run_id = 'sim_test_num'").fetchone()

        assert row_null[0] is None
        assert row_zero[0] == 0.0
        assert row_num[0] == 12.45
