def test_pure_cbr_filtering_and_nrl(tmp_path: Path):
    """
    Verifies that:
    1. AODV control messages (port 654) and unclassified flows are excluded from PDR and Delay.
    2. PDR is computed solely from pure CBR user-data: 32 / 40 = 80.0%.
    3. Delay is computed solely from received CBR packets: 100,000,000 ns / 32 = 3.125 ms -> rounded to 3.12 ms.
    4. NRL is computed as routing_control_packets / received CBR packets: 64 / 32 = 2.0.
    """
    xml_file = tmp_path / "flowmon.xml"
    xml_file.write_text(SAMPLE_FLOWMON_WITH_AODV_AND_CBR, encoding="utf-8")

    metrics = parse_flowmon_xml(xml_file, routing_control_packets=64)

    # Pure CBR data: tx=40, rx=32, lost=8
    assert metrics["tx_packets"] == 40
    assert metrics["rx_packets"] == 32
    assert metrics["lost_packets"] == 8
    assert metrics["pdr"] == 80.0
    assert metrics["delay_ms"] == 3.12
    assert metrics["overhead_ratio"] == 2.0  # 64 / 32


def test_zero_delivery_flow_nrl_none(tmp_path: Path):
    """
    Verifies that when zero CBR data packets are received:
    - PDR is 0.0%
    - Delay is None (mathematically undefined due to zero delivered packets)
    - NRL is None (undefined division by zero), not a fabricated fallback.
    """
    xml_file = tmp_path / "zero_flowmon.xml"
