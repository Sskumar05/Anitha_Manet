def test_multiple_cbr_flows_delay_aggregation(tmp_path: Path):
    """
    Verifies that multiple CBR flows aggregate delay correctly:
    Flow 2: 20 rx pkts, delaySum = 40 ms
    Flow 3: 30 rx pkts, delaySum = 90 ms
    Total RX = 50 pkts, Total delaySum = 130 ms -> avg = 130 / 50 = 2.6 ms.
    AODV Control Flow 1 is excluded from RX count and delaySum.
    """
    xml_file = tmp_path / "multi_cbr.xml"
    xml_file.write_text(SAMPLE_FLOWMON_MULTI_CBR, encoding="utf-8")

    metrics = parse_flowmon_xml(xml_file, routing_control_packets=100)

    assert metrics["tx_packets"] == 60  # 25 + 35
    assert metrics["rx_packets"] == 50  # 20 + 30
    assert metrics["lost_packets"] == 10 # 5 + 5
    assert metrics["pdr"] == round(50 / 60 * 100.0, 2)  # 83.33%
    assert metrics["delay_ms"] == 2.6  # 130,000,000 ns / 50 / 1e6 = 2.6 ms
    assert metrics["overhead_ratio"] == 2.0  # 100 / 50


